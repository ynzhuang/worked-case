def _case_metrics(matrix: ConfusionMatrix) -> dict[str, Any]:
    """PPV and sensitivity for `case`, with not-ascertainable reported apart.

    The not-ascertainable rate is computed over everything the definition was
    asked about, because that is the number a reader needs: how much of the
    cohort question this corpus simply cannot answer.
    """
    tp = matrix.get("case", "case")
    fp = sum(matrix.get(g, "case") for g in matrix.labels if g != "case")
    fn = sum(matrix.get("case", p) for p in matrix.labels if p != "case")
    prf = PRF(tp=tp, fp=fp, fn=fn)
    predicted_na = sum(matrix.get(g, "not_ascertainable") for g in matrix.labels)
    true_na = sum(matrix.get("not_ascertainable", p) for p in matrix.labels)
    return {
        "ppv": round(prf.precision, 4),
        "sensitivity": round(prf.recall, 4),
        "f1": round(prf.f1, 4),
        "tp": tp, "fp": fp, "fn": fn,
        "gold_cases": prf.support,
        "predicted_cases": prf.predicted,
        "episodes": matrix.total,
        "not_ascertainable_predicted": predicted_na,
        "not_ascertainable_gold": true_na,
        "not_ascertainable_rate": round(predicted_na / matrix.total, 4)
        if matrix.total else 0.0,
        "not_ascertainable_agreement": round(
            matrix.get("not_ascertainable", "not_ascertainable") / true_na, 4
        ) if true_na else 0.0,
    }


def run_evaluation(
    pipeline: Pipeline | None = None,
    definition_id: str = "te_truncal_rash",
    version: int | None = None,
    report_path: str | Path | None = None,
    holdout: Sequence[str] | None = None,
) -> tuple[dict[str, Any], Path | None]:
    pipeline = pipeline or Pipeline.load(store_path=paths.STORE_DB)
    if version is None:
        recorded = str(pipeline.store.manifest.get("gold_case_definition") or "")
        if recorded.startswith(f"{definition_id}.v"):
            try:
                version = int(recorded.rsplit(".v", 1)[-1])
            except ValueError:
                version = None
    definition = pipeline.definition(definition_id, version)
    results = EvaluationHarness.build(pipeline, definition).run_all(holdout)

    written: Path | None = None
    if report_path is not None:
        from .report import render_markdown

        target = Path(report_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_markdown(results), encoding="utf-8")
        written = target
    return results, written
