"""The evaluation harness.

Five things, reported separately because they answer different questions.

**Phenotype.** PPV and sensitivity against the gold verdicts, with the
**not-ascertainable rate** as a first-class number per study rather than a
footnote. An episode nobody can evaluate is not a negative, and averaging it
into one would overstate both the numerator and the denominator's meaning.

**Value ablation.** The same definition run twice: structured attributes only,
then with text recovery enabled. The fraction of qualifying events findable
*only* through text is the business case for the whole layer, so it is a named
output rather than something a reader has to derive.

**Availability confusion matrix.** Does the system tell "no location recorded"
from "no location"? Confusing those is the failure that quietly biases every
downstream estimate, and it is the one a single accuracy number hides.

**Representation invariance.** The same clinical truth rendered under six
profiles: does the verdict agree wherever the evidence supports it? Consistency
across representations is not clinical validity, and the report says so in those
words.

**Reproducibility.** Identical inputs produce an identical run hash, and a
recorded run replays against a superseded definition.

Transportability lives in ``transport.py`` and the silver standard in
``silver.py``; both are reported alongside these.
"""

from __future__ import annotations

import collections
import datetime as _dt
from dataclasses import dataclass, field as _dc_field
from pathlib import Path
from typing import Any, Iterable, Sequence

from .. import paths
from ..hashing import hash_payload
from ..models import (
    AVAILABILITY_VALUES,
    VERDICTS,
    CanonicalAEEpisode,
    CaseAssignment,
    PhenotypeDefinition,
)
from ..pipeline import Pipeline
from ..runs import execute
from ..silver import SilverHarness
from .metrics import ConfusionMatrix, PRF

DISCLAIMER = (
    "All numbers below are computed on a synthetic corpus generated by this "
    "repository. Gold labels are the generator's intent, so these figures "
    "measure whether the pipeline recovers a signal that was deliberately "
    "planted. They are not an estimate of performance on real clinical text."
)

INVARIANCE_CAVEAT = (
    "Consistency across representations is not clinical validity. A pipeline "
    "can be perfectly consistent and consistently wrong. This section is a "
    "robustness check layered on the phenotype and extraction numbers; it does "
    "not replace them, and a high agreement rate here is not evidence that the "
    "case definition is clinically correct."
)

ABLATION_NOTE = (
    "The ablation runs the same frozen definition twice on the same episodes: "
    "once accepting only structured routes, once accepting text as well. The "
    "difference is what the extraction layer is worth on this corpus, stated as "
    "a count of events rather than as a score."
)


@dataclass
class EvaluationHarness:
    pipeline: Pipeline
    definition: PhenotypeDefinition
    episodes: list[CanonicalAEEpisode] = _dc_field(default_factory=list)
    assignments: list[CaseAssignment] = _dc_field(default_factory=list)

    @classmethod
    def build(
        cls, pipeline: Pipeline, definition: PhenotypeDefinition
    ) -> "EvaluationHarness":
        episodes = pipeline.episodes()
        return cls(
            pipeline=pipeline, definition=definition, episodes=episodes,
            assignments=pipeline.evaluate(definition, episodes=episodes),
        )

    # -- gold ---------------------------------------------------------------

    def gold_by_episode(self) -> dict[str, dict[str, Any]]:
        """Gold keyed by the episode it belongs to.

        Gold is written per rendered event; an episode is derived. They are
        matched on the source records, which is the only join that survives a
        study splitting one event across rows.
        """
        by_record: dict[str, dict[str, Any]] = {}
        for entry in self.pipeline.store.gold_episodes():
            for record_id in entry["source_record_ids"]:
                by_record[record_id] = entry
        matched: dict[str, dict[str, Any]] = {}
        for episode in self.episodes:
            for record_id in episode.source_record_ids:
                if record_id in by_record:
                    matched[episode.episode_id] = by_record[record_id]
                    break
        return matched

    # -- phenotype ----------------------------------------------------------

    def phenotype(self) -> dict[str, Any]:
        gold = self.gold_by_episode()
        matrix = ConfusionMatrix(labels=list(VERDICTS))
        per_study: dict[str, ConfusionMatrix] = {}
        per_profile: dict[str, ConfusionMatrix] = {}

        for assignment in self.assignments:
            truth = gold.get(assignment.episode_id)
            if truth is None:
                continue
            matrix.add(truth["true_verdict"], assignment.verdict)
            per_study.setdefault(
                assignment.study_id, ConfusionMatrix(labels=list(VERDICTS))
            ).add(truth["true_verdict"], assignment.verdict)
            per_profile.setdefault(
                assignment.profile, ConfusionMatrix(labels=list(VERDICTS))
            ).add(truth["true_verdict"], assignment.verdict)

        return {
            "evaluated_definition": self.definition.key,
            "episodes": len(self.assignments),
            "matched_to_gold": matrix.total,
            "pooled": _case_metrics(matrix),
            "verdict_confusion": matrix.to_dict(),
            "verdict_matrix": matrix,
            "counts_by_verdict": dict(
                sorted(collections.Counter(
                    a.verdict for a in self.assignments
                ).items())
            ),
            "per_study": {s: _case_metrics(m) for s, m in sorted(per_study.items())},
            "per_profile": {
                p: _case_metrics(m) for p, m in sorted(per_profile.items())
            },
            "attribute_sources": dict(sorted(collections.Counter(
                variable for a in self.assignments if a.verdict == "case"
                for variable in a.attribute_sources.values()
            ).items())),
            "attribute_methods": dict(sorted(collections.Counter(
                method for a in self.assignments if a.verdict == "case"
                for method in a.attribute_methods.values()
            ).items())),
            "cases_depending_on_text": sum(
                1 for a in self.assignments
                if a.verdict == "case" and a.used_text_extraction
            ),
        }

    # -- value ablation -----------------------------------------------------

    def ablation(self) -> dict[str, Any]:
        """What text recovery is worth, as a count of events.

        Both arms run the same frozen definition over the same episodes. The
        structured arm is produced by narrowing the accepted routes, not by
        re-running the pipeline, so nothing else differs between them.
        """
        structured_only = self.definition.model_copy(deep=True)
        for requirement in structured_only.required_attributes:
            requirement.accept_methods = [
                m for m in requirement.accept_methods if m != "extracted"
            ] or ["direct"]

        with_text = {a.episode_id: a for a in self.assignments}
        without_text = {
            a.episode_id: a
            for a in self.pipeline.evaluate(structured_only, episodes=self.episodes)
        }

        text_only: list[dict[str, Any]] = []
        for episode_id, assignment in sorted(with_text.items()):
            other = without_text.get(episode_id)
            if assignment.verdict == "case" and (other is None or other.verdict != "case"):
                text_only.append({
                    "episode_id": episode_id,
                    "study_id": assignment.study_id,
                    "profile": assignment.profile,
                    "without_text": other.verdict if other else None,
                    "attribute_sources": assignment.attribute_sources,
                })

        cases_with = sum(1 for a in with_text.values() if a.verdict == "case")
        cases_without = sum(1 for a in without_text.values() if a.verdict == "case")
        na_with = sum(
            1 for a in with_text.values() if a.verdict == "not_ascertainable"
        )
        na_without = sum(
            1 for a in without_text.values() if a.verdict == "not_ascertainable"
        )
        return {
            "note": ABLATION_NOTE,
            "cases_structured_only": cases_without,
            "cases_with_text": cases_with,
            "cases_only_findable_through_text": len(text_only),
            "fraction_only_findable_through_text": round(
                len(text_only) / cases_with, 4
            ) if cases_with else 0.0,
            "not_ascertainable_structured_only": na_without,
            "not_ascertainable_with_text": na_with,
            "not_ascertainable_resolved_by_text": na_without - na_with,
            "examples": text_only[:10],
            "by_profile": dict(sorted(collections.Counter(
                row["profile"] for row in text_only
            ).items())),
        }

    # -- availability -------------------------------------------------------

    def availability(self, attribute: str = "location") -> dict[str, Any]:
        """Does the system tell the kinds of missing apart?

        Scored per source record against the generator's own availability
        labels, because that is where the distinction is made or lost.
        """
        gold = {g["source_record_id"]: g for g in self.pipeline.store.gold_records()}
        matrix = ConfusionMatrix(labels=list(AVAILABILITY_VALUES))
        confusions: list[dict[str, Any]] = []

        for record in self.pipeline.records():
            truth = gold.get(record.source_record_id)
            if truth is None:
                continue
            expected = (truth.get("availability") or {}).get(attribute)
            if expected is None:
                continue
            found = record.attribute(attribute)
            actual = found.availability if found else "unknown"
            matrix.add(expected, actual)
            if expected != actual:
                confusions.append({
                    "source_record_id": record.source_record_id,
                    "profile": record.profile,
                    "expected": expected,
                    "actual": actual,
                    "note": found.note if found else "",
                })

        collected_read_as_missing = sum(
            matrix.get("collected", p) for p in matrix.labels if p != "collected"
        )
        missing_read_as_collected = sum(
            matrix.get(g, "collected") for g in matrix.labels if g != "collected"
        )
        return {
            "attribute": attribute,
            "confusion": matrix.to_dict(),
            "matrix": matrix,
            "accuracy": matrix.accuracy,
            "collected_read_as_missing": collected_read_as_missing,
            "missing_read_as_collected": missing_read_as_collected,
            "not_collected_read_as_unknown": matrix.get(
                "not_collected_by_protocol", "unknown"
            ),
            "examples": confusions[:10],
        }

    # -- invariance ---------------------------------------------------------

    def invariance(self) -> dict[str, Any]:
        """One truth, six renderings: does the verdict agree where it can?"""
        gold = self.gold_by_episode()
        by_truth: dict[str, dict[str, dict[str, Any]]] = collections.defaultdict(dict)
        for assignment in self.assignments:
            truth = gold.get(assignment.episode_id)
            if truth is None or truth.get("cohort") != "shared":
                continue
            by_truth[truth["truth_id"]][assignment.profile] = {
                "verdict": assignment.verdict,
                "reference": truth["verdict_if_location_available"],
                "location_available": truth["location_available"],
                "reason": assignment.reason,
            }

        comparable = {t: b for t, b in by_truth.items() if len(b) >= 2}
        agreeing = 0
        # Agreement *where the evidence supports it*: a rendering that could not
        # record the location is not expected to reach the same verdict, and
        # counting it as a disagreement would punish the system for the study's
        # collection decision.
        supported_agreeing = 0
        supported_total = 0
        discordant: list[dict[str, Any]] = []

        for truth_id, body in sorted(comparable.items()):
            verdicts = {v["verdict"] for v in body.values()}
            if len(verdicts) == 1:
                agreeing += 1
            supported = {
                p: v for p, v in body.items() if v["location_available"]
            }
            if supported:
                supported_total += 1
                if len({v["verdict"] for v in supported.values()}) == 1:
                    supported_agreeing += 1
                else:
                    discordant.append({
                        "truth_id": truth_id,
                        "reference": next(iter(body.values()))["reference"],
                        "verdicts": {p: v["verdict"] for p, v in sorted(body.items())},
                        "example_reason": sorted(supported.items())[0][1]["reason"],
                    })

        total = len(comparable)
        return {
            "caveat": INVARIANCE_CAVEAT,
            "truths_compared": total,
            "raw_agreement": round(agreeing / total, 4) if total else 0.0,
            "agreement_where_evidence_supports_it": round(
                supported_agreeing / supported_total, 4
            ) if supported_total else 0.0,
            "truths_with_supporting_evidence": supported_total,
            "discordant_count": len(discordant),
            "discordant": discordant[:20],
            "verdicts_by_profile": {
                profile: dict(sorted(collections.Counter(
                    body[profile]["verdict"] for body in comparable.values()
                    if profile in body
                ).items()))
                for profile in sorted(
                    {p for body in comparable.values() for p in body}
                )
            },
        }

    # -- reproducibility ----------------------------------------------------

    def reproducibility(self, repeats: int = 2) -> dict[str, Any]:
        manifest_ids: list[str] = []
        result_hashes: list[str] = []
        record_hashes: list[str] = []
        for _ in range(repeats):
            records = self.pipeline.records(refresh=True)
            record_hashes.append(
                hash_payload([r.model_dump(mode="json") for r in records], length=32)
            )
            manifest, _assignments = execute(
                self.pipeline, self.definition, save=False
            )
            manifest_ids.append(manifest.manifest_id)
            result_hashes.append(manifest.results_hash)
        return {
            "repeats": repeats,
            "manifest_ids": manifest_ids,
            "result_hashes": result_hashes,
            "manifest_id_stable": len(set(manifest_ids)) == 1,
            "results_stable": len(set(result_hashes)) == 1,
            "normalization_stable": len(set(record_hashes)) == 1,
        }

    # -- silver and transport ----------------------------------------------

    def silver(self, attribute: str = "location") -> dict[str, Any]:
        harness = SilverHarness(
            self.pipeline.configs, self.pipeline.store, self.pipeline.engine()
        )
        return harness.run(self.pipeline.records(), attribute).to_dict()

    def transport(self, holdout: Sequence[str] | None = None) -> dict[str, Any]:
        from .transport import transportability

        return transportability(self.pipeline, self.definition, holdout)

    # -- everything ---------------------------------------------------------

    def run_all(self, holdout: Sequence[str] | None = None) -> dict[str, Any]:
        return {
            "generated_at": _dt.datetime.now(_dt.timezone.utc).isoformat(
                timespec="seconds"
            ),
            "disclaimer": DISCLAIMER,
            "versions": self.pipeline.versions(),
            "definition": {
                "id": self.definition.id,
                "version": self.definition.version,
                "status": self.definition.status,
                "hash": self.definition.definition_hash,
                "label": self.definition.label,
            },
            "corpus": {
                **self.pipeline.store.summary(),
                "records": len(self.pipeline.records()),
                "episodes": len(self.episodes),
            },
            "phenotype": self.phenotype(),
            "ablation": self.ablation(),
            "availability": self.availability(),
            "silver": self.silver(),
            "transport": self.transport(holdout),
            "invariance": self.invariance(),
            "reproducibility": self.reproducibility(),
        }


