"""The evaluation harness.

Seven sections, reported separately because they answer different questions and
averaging them would hide the one that matters.

**Phenotype.** PPV and sensitivity against the gold verdicts, with the
**not-ascertainable rate** as a first-class number per study rather than a
footnote. A record nobody can evaluate is not a negative, and averaging it into
one would overstate both the numerator and the denominator's meaning.

**Denominators.** The ascertainable fraction per study, beside every rate.

**Value ablation.** Three cumulative stages ending in a stated decision. This
and the silver standard are the two sections the whole prototype exists to
produce; see ``ablation.py``.

**Silver standard.** Extraction scored against a masked structured comparator,
with calibration — and with two caveats printed verbatim, because agreement
between two routes written by the same investigator is an upper bound, and the
studies that can be scored at all are not a random subset.

**Assertion confusion.** Does the system tell a documented "no" from silence?
Confusing those is the failure that quietly biases every rate, and it is
exactly the one a single accuracy number hides.

**Representation invariance.** One clinical truth rendered under seven
profiles: does the verdict agree wherever the evidence supports it? Consistency
across representations is not clinical validity, and the report says so in
those words.

**Reproducibility.** Identical inputs produce an identical run hash.

Transportability lives in ``transport.py`` and is reported alongside.
"""

