"""The evaluation harness.

Three layers, a stress test, and a reproducibility check.  They answer different
questions and are reported separately on purpose.

**Layer 1, clinical validity.**  Does the pipeline recover what the source
says?  Field-level precision, recall and F1 against gold, broken out by
collection state and by which path produced the value.  Plus a collection-state
confusion matrix, and abstention quality: how often the model path correctly
declined versus guessed wrong.

**Layer 2, episode reconciliation.**  Do the derived episodes match the true
boundaries?  Over-merge and over-split reported separately, and separately again
for concepts where recurrence is expected, because that is where the default
rule is wrong.

**Layer 3, phenotype.**  PPV and sensitivity against the gold case labels, plus
cross-study transportability: performance on studies held out from development,
and the drop.

**Stress test, representation invariance.**  For each sampled truth, does the
final classification agree across the six renderings?  This is layered on top of
Layers 1-3 and **consistency across representations does not establish clinical
validity** — a pipeline can be perfectly consistent and consistently wrong.  The
report says so in those words.

**Reproducibility.**  Identical inputs produce an identical run hash, and a
recorded run replays against a superseded definition.
"""

from __future__ import annotations

import collections
import datetime as _dt
from dataclasses import dataclass, field as _dc_field
from pathlib import Path
from typing import Any, Iterable, Sequence

from .. import paths
from ..hashing import hash_payload
from ..models import (
    COLLECTION_STATES,
    CanonicalAEEpisode,
    CanonicalAERecord,
    PhenotypeDefinition,
)
from ..pipeline import Pipeline
from ..runs import execute
from .metrics import ConfusionMatrix, PRF, scalar_prf, set_prf

#: Fields compared against gold at record level.
_COMPARED_FIELDS = (
    "verbatim_term", "coded_term", "severity", "relatedness", "action_taken",
    "outcome", "onset_datetime", "end_datetime",
)

#: Studies used while developing the rules, and studies held out from it.
#: Nothing here is fitted to data, so the gap measures representation
#: difficulty rather than overfitting, and the report says so.
DEVELOPMENT_STUDIES = ("STUDY-01", "STUDY-02", "STUDY-03")

DISCLAIMER = (
    "All numbers below are computed on a synthetic corpus generated by this "
    "repository. Gold labels are the generator's intent, so these figures "
    "measure whether the pipeline recovers a signal that was deliberately "
    "planted. They are not an estimate of performance on real clinical text."
)

INVARIANCE_CAVEAT = (
    "Consistency across representations does not establish clinical validity. "
    "A pipeline can be perfectly consistent and consistently wrong. This "
    "section is a robustness check layered on Layers 1-3; it does not replace "
    "them, and a high agreement rate here is not evidence that the case "
    "definition is clinically correct."
)


def _iso(value: Any) -> Any:
    if isinstance(value, (_dt.datetime, _dt.date)):
        return value.isoformat()
    return value


@dataclass
class EvaluationHarness:
    pipeline: Pipeline
    definition: PhenotypeDefinition
    records: list[CanonicalAERecord] = _dc_field(default_factory=list)
    episodes: list[CanonicalAEEpisode] = _dc_field(default_factory=list)

    @classmethod
    def build(
        cls, pipeline: Pipeline, definition: PhenotypeDefinition
    ) -> "EvaluationHarness":
        return cls(
            pipeline=pipeline,
            definition=definition,
            records=pipeline.records(),
            episodes=pipeline.episodes(),
        )

    # -- Layer 1 ------------------------------------------------------------

    def layer1_clinical_validity(self) -> dict[str, Any]:
        gold = self.pipeline.store.gold_records_by_id()
        overall: dict[str, PRF] = collections.defaultdict(PRF)
        by_state: dict[str, dict[str, PRF]] = collections.defaultdict(
            lambda: collections.defaultdict(PRF)
        )
        by_path: dict[str, dict[str, PRF]] = collections.defaultdict(
            lambda: collections.defaultdict(PRF)
        )
        by_representation: dict[str, dict[str, PRF]] = collections.defaultdict(
            lambda: collections.defaultdict(PRF)
        )
        state_matrix = ConfusionMatrix(labels=list(COLLECTION_STATES))
        abstention = {
            "correct_abstention": 0, "wrong_abstention": 0,
            "correct_answer": 0, "wrong_answer": 0,
        }
        violations: list[str] = []

        for record in self.records:
            truth = gold.get(record.source_record_id)
            if truth is None:
                continue
            if not record.has_full_provenance():
                violations.append(
                    f"{record.source_record_id}: {record.missing_provenance()}"
                )
            representation = truth.get("representation", "?")
            fields = record.fields()

            for name in _COMPARED_FIELDS:
                field = fields.get(name)
                if field is None:
                    continue
                # Compared against how the *deterministic* path left the field.
                # A value the model later recovered does not retroactively make
                # the CRF column collected, and conflating the two would hide
                # the distinction this whole layer exists to preserve.
                want_state = truth["collection_states"].get(name)
                if want_state:
                    state_matrix.add(want_state, field.structured_state)

                # Compared against what the record as a whole supports: the
                # structured cell where there is one, the narrative where the
                # study left the column out. Comparing against the cell alone
                # would score a correct narrative recovery as a wrong answer.
                want_value = (
                    truth.get("recoverable_values", truth["values"]).get(name)
                )
                got_value = _iso(field.value)
                counts = scalar_prf(want_value, got_value)
                overall[name].add(*counts)
                if want_state:
                    by_state[want_state][name].add(*counts)
                by_path[field.source][name].add(*counts)
                by_representation[representation][name].add(*counts)

                # Abstention quality, scored only where the model path was
                # actually asked. A field it answered carries source "text"; a
                # field it declined keeps its original source and is marked in
                # the note, which is how declining stays visible at all.
                declined = "abstained" in (field.note or "")
                if field.source == "text":
                    if got_value == want_value:
                        abstention["correct_answer"] += 1
                    else:
                        abstention["wrong_answer"] += 1
                elif declined:
                    if want_value is None:
                        abstention["correct_abstention"] += 1
                    else:
                        abstention["wrong_abstention"] += 1

            for criterion, field in record.seriousness_criteria.items():
                key = f"seriousness_criteria.{criterion}"
                want_state = truth["collection_states"].get(key)
                if want_state:
                    state_matrix.add(want_state, field.collection_state)
                counts = scalar_prf(truth["values"].get(key), field.value)
                overall["seriousness_criteria"].add(*counts)

        answered = abstention["correct_answer"] + abstention["wrong_answer"]
        declined = abstention["correct_abstention"] + abstention["wrong_abstention"]
        return {
            "records": len(self.records),
            "overall": {k: v.to_dict() for k, v in sorted(overall.items())},
            "by_collection_state": {
                state: {f: p.to_dict() for f, p in sorted(fields.items())}
                for state, fields in sorted(by_state.items())
            },
            "by_source_path": {
                path: {f: p.to_dict() for f, p in sorted(fields.items())}
                for path, fields in sorted(by_path.items())
            },
            "by_representation": {
                rep: {f: p.to_dict() for f, p in sorted(fields.items())}
                for rep, fields in sorted(by_representation.items())
            },
            "collection_state_confusion": state_matrix.to_dict(),
            "collection_state_matrix": state_matrix,
            "abstention": {
                **abstention,
                "abstention_precision": round(
                    abstention["correct_abstention"] / declined, 4
                ) if declined else 0.0,
                "answer_precision": round(
                    abstention["correct_answer"] / answered, 4
                ) if answered else 0.0,
            },
            "provenance_violations": violations,
        }

    # -- Layer 2 ------------------------------------------------------------

    def layer2_episodes(self) -> dict[str, Any]:
        gold = self.pipeline.store.gold_episodes()
        gold_sets = [frozenset(g["source_record_ids"]) for g in gold]
        gold_index: dict[str, int] = {}
        for index, entry in enumerate(gold):
            for record_id in entry["source_record_ids"]:
                gold_index[record_id] = index

        predicted_sets = [frozenset(e.source_record_ids) for e in self.episodes]
        predicted_index: dict[str, int] = {}
        for index, episode in enumerate(self.episodes):
            for record_id in episode.source_record_ids:
                predicted_index[record_id] = index

        exact = set(gold_sets) & set(predicted_sets)
        over_merged = [
            e for e in self.episodes
            if len({gold_index.get(r) for r in e.source_record_ids}) > 1
        ]
        over_split = [
            g for g in gold
            if len({predicted_index.get(r) for r in g["source_record_ids"]}) > 1
        ]

        def rate(entries: Sequence[dict[str, Any]], recurrent: bool) -> dict[str, Any]:
            subset = [
                g for g in entries
                if self._recurs(g.get("concept")) is recurrent
            ]
            if not subset:
                return {"episodes": 0, "over_split": 0, "over_split_rate": 0.0}
            split = [
                g for g in subset
                if len({predicted_index.get(r) for r in g["source_record_ids"]}) > 1
            ]
            return {
                "episodes": len(subset),
                "over_split": len(split),
                "over_split_rate": round(len(split) / len(subset), 4),
            }

        by_representation = collections.Counter(
            g["representation"] for g in gold
            if frozenset(g["source_record_ids"]) not in set(predicted_sets)
        )
        return {
            "gold_episodes": len(gold),
            "derived_episodes": len(self.episodes),
            "exact_boundary_matches": len(exact),
            "boundary_agreement": round(len(exact) / len(gold_sets), 4) if gold_sets else 0.0,
            "over_merge": len(over_merged),
            "over_merge_rate": round(len(over_merged) / len(self.episodes), 4)
            if self.episodes else 0.0,
            "over_split": len(over_split),
            "over_split_rate": round(len(over_split) / len(gold_sets), 4)
            if gold_sets else 0.0,
            "recurrence_expected": rate(gold, True),
            "recurrence_not_expected": rate(gold, False),
            "mismatches_by_representation": dict(sorted(by_representation.items())),
            "linkage_rules": dict(
                sorted(collections.Counter(e.linkage_rule for e in self.episodes).items())
            ),
            "flagged_for_review": sum(
                1 for e in self.episodes if e.linkage_review_required
            ),
        }

    def _recurs(self, concept: str | None) -> bool:
        if not concept:
            return True
        try:
            return self.pipeline.catalog.concept(concept).recurrence_expected
        except Exception:
            return True

    # -- Layer 3 ------------------------------------------------------------

    def layer3_phenotype(self) -> dict[str, Any]:
        assignments = self.pipeline.evaluate(self.definition)
        gold = self.pipeline.store.gold_episodes()
        gold_by_subject: dict[str, list[dict[str, Any]]] = collections.defaultdict(list)
        for entry in gold:
            gold_by_subject[entry["subject_id"]].append(entry)
        predicted_by_subject: dict[str, list[Any]] = collections.defaultdict(list)
        for assignment in assignments:
            predicted_by_subject[assignment.subject_id].append(assignment)

        matrix = ConfusionMatrix(labels=["case", "review", "excluded"])
        per_study: dict[str, ConfusionMatrix] = {}
        for subject, entries in gold_by_subject.items():
            predicted = sorted(
                predicted_by_subject.get(subject, []), key=lambda a: a.episode_id
            )
            for index, entry in enumerate(
                sorted(entries, key=lambda g: g["episode_index"])
            ):
                if index >= len(predicted):
                    continue
                want = entry["verdict_as_recorded"]
                got = predicted[index].verdict
                matrix.add(want, got)
                per_study.setdefault(
                    entry["study_id"],
                    ConfusionMatrix(labels=["case", "review", "excluded"]),
                ).add(want, got)

        def ppv_sensitivity(cm: ConfusionMatrix) -> dict[str, Any]:
            tp = cm.get("case", "case")
            fp = sum(cm.get(g, "case") for g in cm.labels if g != "case")
            fn = sum(cm.get("case", p) for p in cm.labels if p != "case")
            prf = PRF(tp=tp, fp=fp, fn=fn)
            return {
                "ppv": round(prf.precision, 4),
                "sensitivity": round(prf.recall, 4),
                "f1": round(prf.f1, 4),
                "tp": tp, "fp": fp, "fn": fn,
                "gold_cases": prf.support, "predicted_cases": prf.predicted,
            }

        development = ConfusionMatrix(labels=["case", "review", "excluded"])
        held_out = ConfusionMatrix(labels=["case", "review", "excluded"])
        for study, cm in per_study.items():
            target = development if study in DEVELOPMENT_STUDIES else held_out
            for (want, got), count in cm.counts.items():
                for _ in range(count):
                    target.add(want, got)

        # A case the system routed to review because the episode boundary was
        # a judgement call is a different kind of miss from one it got wrong.
        # Pooling them would read as an accuracy problem when it is the system
        # declining to assert something it cannot settle.
        declined = 0
        for subject, entries in gold_by_subject.items():
            predicted = sorted(
                predicted_by_subject.get(subject, []), key=lambda a: a.episode_id
            )
            for index, entry in enumerate(
                sorted(entries, key=lambda g: g["episode_index"])
            ):
                if index >= len(predicted):
                    continue
                assignment = predicted[index]
                if (
                    entry["verdict_as_recorded"] == "case"
                    and assignment.verdict == "review"
                    and assignment.linkage_review_required
                ):
                    declined += 1

        pooled = ppv_sensitivity(matrix)
        pooled["false_negatives_from_linkage_review"] = declined
        pooled["false_negatives_other"] = pooled["fn"] - declined
        pooled["sensitivity_excluding_declined"] = round(
            pooled["tp"] / (pooled["tp"] + pooled["false_negatives_other"]), 4
        ) if (pooled["tp"] + pooled["false_negatives_other"]) else 0.0
        development_result = ppv_sensitivity(development)
        held_out_result = ppv_sensitivity(held_out)
        return {
            "evaluated_definition": self.definition.key,
            "episodes": len(assignments),
            "pooled": pooled,
            "per_study": {s: ppv_sensitivity(cm) for s, cm in sorted(per_study.items())},
            "verdict_confusion": matrix.to_dict(),
            "verdict_matrix": matrix,
            "counts_by_verdict": dict(
                sorted(collections.Counter(a.verdict for a in assignments).items())
            ),
            "counts_by_state": dict(
                sorted(
                    collections.Counter(a.evidence_state for a in assignments).items()
                )
            ),
            "review_set_size": sum(1 for a in assignments if a.verdict == "review"),
            "transportability": {
                "development_studies": list(DEVELOPMENT_STUDIES),
                "held_out_studies": sorted(
                    s for s in per_study if s not in DEVELOPMENT_STUDIES
                ),
                "development": development_result,
                "held_out": held_out_result,
                "sensitivity_drop": round(
                    development_result["sensitivity"] - held_out_result["sensitivity"], 4
                ),
                "ppv_drop": round(
                    development_result["ppv"] - held_out_result["ppv"], 4
                ),
                "note": (
                    "Nothing in this pipeline is fitted to data, so this gap "
                    "measures how much harder the held-out studies' collection "
                    "conventions are, not overfitting to the development set."
                ),
            },
        }

    # -- Invariance ---------------------------------------------------------

    def invariance(self) -> dict[str, Any]:
        """Does the same truth reach the same conclusion under six renderings?"""
        assignments = {a.episode_id: a for a in self.pipeline.evaluate(self.definition)}
        gold = self.pipeline.store.gold_episodes()
        predicted_by_subject: dict[str, list[Any]] = collections.defaultdict(list)
        for assignment in assignments.values():
            predicted_by_subject[assignment.subject_id].append(assignment)

        by_truth: dict[str, dict[str, Any]] = collections.defaultdict(dict)
        for entry in gold:
            predicted = sorted(
                predicted_by_subject.get(entry["subject_id"], []),
                key=lambda a: a.episode_id,
            )
            index = entry["episode_index"]
            if index >= len(predicted):
                continue
            by_truth[entry["truth_id"]][entry["representation"]] = {
                "verdict": predicted[index].verdict,
                "state": predicted[index].evidence_state,
                "reference_verdict": entry["true_verdict"],
                "study_id": entry["study_id"],
                "episode_id": predicted[index].episode_id,
                "reason": predicted[index].reason,
            }

        # Only truths rendered in every variant can be compared.
        comparable = {
            truth_id: body for truth_id, body in by_truth.items() if len(body) >= 2
        }
        agreeing_verdict = 0
        agreeing_state = 0
        discordant: list[dict[str, Any]] = []
        pair_matrix: dict[str, collections.Counter] = collections.defaultdict(
            collections.Counter
        )
        for truth_id, body in sorted(comparable.items()):
            verdicts = {v["verdict"] for v in body.values()}
            states = {v["state"] for v in body.values()}
            if len(verdicts) == 1:
                agreeing_verdict += 1
            else:
                majority = collections.Counter(
                    v["verdict"] for v in body.values()
                ).most_common(1)[0][0]
                for representation, value in sorted(body.items()):
                    if value["verdict"] != majority:
                        pair_matrix[representation][value["verdict"]] += 1
                discordant.append(
                    {
                        "truth_id": truth_id,
                        "reference_verdict": next(iter(body.values()))["reference_verdict"],
                        "verdicts": {r: v["verdict"] for r, v in sorted(body.items())},
                        "states": {r: v["state"] for r, v in sorted(body.items())},
                        "majority": majority,
                        "example_reason": sorted(body.items())[0][1]["reason"],
                    }
                )
            if len(states) == 1:
                agreeing_state += 1

        total = len(comparable)
        return {
            "caveat": INVARIANCE_CAVEAT,
            "truths_compared": total,
            "verdict_agreement": round(agreeing_verdict / total, 4) if total else 0.0,
            "state_agreement": round(agreeing_state / total, 4) if total else 0.0,
            "discordant_count": len(discordant),
            "discordant": discordant[:25],
            "discordance_by_representation": {
                rep: dict(counts) for rep, counts in sorted(pair_matrix.items())
            },
            "representations": sorted(
                {r for body in comparable.values() for r in body}
            ),
        }

    # -- Reproducibility ----------------------------------------------------

    def reproducibility(self, repeats: int = 2) -> dict[str, Any]:
        manifest_ids: list[str] = []
        result_hashes: list[str] = []
        record_hashes: list[str] = []
        for _ in range(repeats):
            records = self.pipeline.records(refresh=True)
            record_hashes.append(
                hash_payload([r.model_dump(mode="json") for r in records], length=32)
            )
            manifest, _assignments = execute(
                self.pipeline, self.definition, save=False
            )
            manifest_ids.append(manifest.manifest_id)
            result_hashes.append(manifest.results_hash)
        return {
            "repeats": repeats,
            "manifest_ids": manifest_ids,
            "result_hashes": result_hashes,
            "record_hashes": record_hashes,
            "manifest_id_stable": len(set(manifest_ids)) == 1,
            "results_stable": len(set(result_hashes)) == 1,
            "normalization_stable": len(set(record_hashes)) == 1,
        }

    # -- Retrieval ----------------------------------------------------------

    def retrieval(self) -> dict[str, Any]:
        try:
            from ..retrieval.query import retrieve
        except ImportError:  # pragma: no cover
            return {"available": False}
        from .retrieval_metrics import evaluate_retrieval

        return evaluate_retrieval(self.pipeline, self.definition)

    # -- everything ---------------------------------------------------------

    def run_all(self) -> dict[str, Any]:
        return {
            "generated_at": _dt.datetime.now(_dt.timezone.utc).isoformat(
                timespec="seconds"
            ),
            "disclaimer": DISCLAIMER,
            "versions": self.pipeline.versions(),
            "definition": {
                "id": self.definition.id, "version": self.definition.version,
                "status": self.definition.status,
                "hash": self.definition.definition_hash,
                "label": self.definition.label,
            },
            "corpus": {
                **self.pipeline.store.summary(),
                "records": len(self.records),
                "episodes": len(self.episodes),
            },
            "layer1": self.layer1_clinical_validity(),
            "layer2": self.layer2_episodes(),
            "layer3": self.layer3_phenotype(),
            "invariance": self.invariance(),
            "reproducibility": self.reproducibility(),
            "retrieval": self.retrieval(),
        }


def run_evaluation(
    pipeline: Pipeline | None = None,
    definition_id: str = "te_symptomatic_hypoglycemia",
    version: int | None = None,
    report_path: str | Path | None = None,
) -> tuple[dict[str, Any], Path | None]:
    pipeline = pipeline or Pipeline.load(store_path=paths.STORE_DB)
    if version is None:
        recorded = str(pipeline.store.manifest.get("gold_case_definition") or "")
        if recorded.startswith(f"{definition_id}.v"):
            try:
                version = int(recorded.rsplit(".v", 1)[-1])
            except ValueError:
                version = None
    definition = pipeline.definition(definition_id, version)
    results = EvaluationHarness.build(pipeline, definition).run_all()

    written: Path | None = None
    if report_path is not None:
        from .report import render_markdown

        target = Path(report_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_markdown(results), encoding="utf-8")
        written = target
    return results, written
