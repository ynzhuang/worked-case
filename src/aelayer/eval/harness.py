#: Fields compared against gold, and how each is compared.
_SCALAR_FIELDS = (
    "assertion",
    "onset_offset_days",
    "severity",
    "relatedness",
    "action_taken",
    "outcome",
    "rechallenge",
    "coded_term",
)
_SET_FIELDS = ("symptoms", "seriousness")
_BOOL_FIELDS = ("rescue_treatment",)

_RECALL_KS = (5, 10, 20, 50)

DISCLAIMER = (
    "All numbers below are computed on a synthetic corpus generated by this "
    "repository. Gold labels are the generator's intent, so these figures "
    "measure whether the pipeline recovers a signal that was deliberately "
    "planted. They are not an estimate of performance on real clinical text."
)


@dataclass
class EvaluationHarness:
    pipeline: Pipeline
    definition: PhenotypeDefinition
    events: list[EventObject] = field(default_factory=list)
    gold: list[dict[str, Any]] = field(default_factory=list)
    gold_cases: dict[str, dict[str, Any]] = field(default_factory=dict)

    @classmethod
    def build(
        cls, pipeline: Pipeline, definition: PhenotypeDefinition
    ) -> "EvaluationHarness":
        gold = pipeline.store.gold()
        gold_cases = {}
        path = pipeline.store.root / "gold_cases.jsonl"
        if path.exists():
            import json

            gold_cases = {
                json.loads(line)["subject_id"]: json.loads(line)
                for line in path.read_text(encoding="utf-8").splitlines()
                if line.strip()
            }
        return cls(
            pipeline=pipeline,
            definition=definition,
            events=pipeline.events(),
            gold=gold,
            gold_cases=gold_cases,
        )

    # -- alignment ----------------------------------------------------------

    def events_by_doc(self) -> dict[str, list[EventObject]]:
        grouped: dict[str, list[EventObject]] = defaultdict(list)
        for event in self.events:
            grouped[event.doc_id].append(event)
        return grouped

    @staticmethod
    def primary_event(events: list[EventObject], concept_id: str) -> EventObject | None:
        """The event object a gold row should be scored against.

        Chosen without consulting gold: among the events for this concept, the
        one with the most concept spans, then the earliest span, then the id.
        Anything that peeked at the gold assertion would make the assertion
        metric meaningless.
        """
        candidates = [e for e in events if e.concept_id == concept_id]
        if not candidates:
            return None

        def key(event: EventObject) -> tuple:
            spans = event.spans_for("concept_id")
            first = min((s.start for s in spans), default=10**9)
            return (-len(spans), first, event.event_id)

        return sorted(candidates, key=key)[0]

    # -- extraction ---------------------------------------------------------

    def extraction_metrics(self) -> dict[str, Any]:
        by_doc = self.events_by_doc()
        overall: dict[str, PRF] = defaultdict(PRF)
        by_assertion: dict[str, dict[str, PRF]] = defaultdict(lambda: defaultdict(PRF))
        by_pattern: dict[str, dict[str, PRF]] = defaultdict(lambda: defaultdict(PRF))
        assertion_matrix = ConfusionMatrix(labels=list(ASSERTION_VALUES))
        onset_by_phrasing: dict[str, PRF] = defaultdict(PRF)
        concept_prf = PRF()
        provenance_violations: list[str] = []

        for row in sorted(self.gold, key=lambda r: r["doc_id"]):
            doc_id = row["doc_id"]
            doc_events = by_doc.get(doc_id, [])
            gold_concept = row.get("concept")
            pattern = row.get("pattern", "unknown")

            # Concept detection: was the right concept raised, and only it?
            predicted_concepts = {e.concept_id for e in doc_events}
            if gold_concept:
                if gold_concept in predicted_concepts:
                    concept_prf.add(tp=1)
                else:
                    concept_prf.add(fn=1)
                concept_prf.add(fp=len(predicted_concepts - {gold_concept}))
            else:
                concept_prf.add(fp=len(predicted_concepts))

            event = self.primary_event(doc_events, gold_concept) if gold_concept else None
            for candidate in doc_events:
                if not candidate.has_full_provenance():
                    provenance_violations.append(
                        f"{candidate.event_id}: {candidate.missing_provenance()}"
                    )
            if event is None:
                continue

            gold_assertion = row.get("assertion") or "present"
            assertion_matrix.add(gold_assertion, event.assertion)

            for field_name in _SCALAR_FIELDS:
                gold_value = row.get(field_name)
                predicted = getattr(event, field_name)
                if field_name == "coded_term":
                    # Compare the preserved dictionary term as written.
                    gold_value = row.get("coded_term")
                counts = scalar_prf(gold_value, predicted)
                overall[field_name].add(*counts)
                by_assertion[gold_assertion][field_name].add(*counts)
                by_pattern[pattern][field_name].add(*counts)
                if field_name == "onset_offset_days":
                    onset_by_phrasing[row.get("onset_phrasing") or "none"].add(*counts)

            gold_symptoms = set(row.get("symptoms") or [])
            predicted_symptoms = {s.symptom for s in event.symptoms}
            counts = set_prf(gold_symptoms, predicted_symptoms)
            overall["symptoms"].add(*counts)
            by_assertion[gold_assertion]["symptoms"].add(*counts)
            by_pattern[pattern]["symptoms"].add(*counts)

            counts = set_prf(set(row.get("seriousness") or []), set(event.seriousness))
            overall["seriousness"].add(*counts)
            by_assertion[gold_assertion]["seriousness"].add(*counts)
            by_pattern[pattern]["seriousness"].add(*counts)

            for field_name in _BOOL_FIELDS:
                gold_value = bool(row.get(field_name))
                predicted = bool(getattr(event, field_name))
                counts = (
                    (1, 0, 0) if gold_value and predicted
                    else (0, 1, 0) if predicted
                    else (0, 0, 1) if gold_value
                    else (0, 0, 0)
                )
                overall[field_name].add(*counts)
                by_assertion[gold_assertion][field_name].add(*counts)
                by_pattern[pattern][field_name].add(*counts)

            gold_labs = {
                (lab["test"], round(float(lab["canonical_mgdl"]), 1))
                for lab in (row.get("labs") or [])
            }
            predicted_labs = {
                (lab.test, round(float(lab.canonical_value), 1))
                for lab in event.labs
                if lab.canonical_value is not None
            }
            # Structured LB rows legitimately add values the narrative never
            # mentioned, so recall is the meaningful figure for labs and extra
            # predictions are not penalised as errors here.
            tp = len(gold_labs & predicted_labs)
            overall["labs"].add(tp=tp, fn=len(gold_labs - predicted_labs))

        return {
            "overall": {k: v.to_dict() for k, v in sorted(overall.items())},
            "concept_detection": concept_prf.to_dict(),
            "assertion_confusion": assertion_matrix.to_dict(),
            "assertion_confusion_matrix": assertion_matrix,
            "assertion_per_label": {
                k: v.to_dict() for k, v in sorted(assertion_matrix.per_label().items())
            },
            "by_assertion": {
                assertion: {f: prf.to_dict() for f, prf in sorted(fields.items())}
                for assertion, fields in sorted(by_assertion.items())
            },
            "by_pattern": {
                pattern: {f: prf.to_dict() for f, prf in sorted(fields.items())}
                for pattern, fields in sorted(by_pattern.items())
            },
            "onset_by_phrasing": {
                k: v.to_dict() for k, v in sorted(onset_by_phrasing.items())
            },
            "provenance_violations": provenance_violations,
            "event_count": len(self.events),
            "gold_record_count": len(self.gold),
        }

    # -- phenotype ----------------------------------------------------------

    @property
    def gold_definition_key(self) -> str:
        """The definition version the gold answer key was built under."""
        return str(
            self.pipeline.store.manifest.get("gold_case_definition")
            or f"{self.definition.id}.v{self.definition.version}"
        )

    def phenotype_metrics(self) -> dict[str, Any]:
        assignments = self.pipeline.evaluate(self.definition)
        evaluated_key = f"{self.definition.id}.v{self.definition.version}"
        matches_gold = evaluated_key == self.gold_definition_key
        matrix = ConfusionMatrix(labels=["case", "review", "excluded"])
        per_study: dict[str, ConfusionMatrix] = {}

        for assignment in assignments:
            gold = self.gold_cases.get(assignment.subject_id)
            if gold is None:
                continue
            matrix.add(gold["verdict"], assignment.verdict)
            study_matrix = per_study.setdefault(
                assignment.study_id, ConfusionMatrix(labels=["case", "review", "excluded"])
            )
            study_matrix.add(gold["verdict"], assignment.verdict)

        state_matrix = ConfusionMatrix(
            labels=["explicit", "supported", "possible", "absent", "none"]
        )
        for assignment in assignments:
            gold = self.gold_cases.get(assignment.subject_id)
            if gold is None:
                continue
            state_matrix.add(gold["evidence_state"], assignment.evidence_state)

        def case_ppv_sensitivity(cm: ConfusionMatrix) -> dict[str, Any]:
            """PPV and sensitivity for the `case` verdict specifically."""
            tp = cm.get("case", "case")
            fp = sum(cm.get(g, "case") for g in cm.labels if g != "case")
            fn = sum(cm.get("case", p) for p in cm.labels if p != "case")
            prf = PRF(tp=tp, fp=fp, fn=fn)
            return {
                "ppv": round(prf.precision, 4),
                "sensitivity": round(prf.recall, 4),
                "f1": round(prf.f1, 4),
                "tp": tp,
                "fp": fp,
                "fn": fn,
                "gold_cases": prf.support,
                "predicted_cases": prf.predicted,
            }

        return {
            "evaluated_definition": evaluated_key,
            "gold_definition": self.gold_definition_key,
            "matches_gold_definition": matches_gold,
            "comparability_note": (
                ""
                if matches_gold
                else (
                    f"PPV and sensitivity below compare {evaluated_key} against a "
                    f"gold key built under {self.gold_definition_key}. The two "
                    f"definitions disagree by design, so these are a measure of "
                    f"how far the versions diverge, not of extraction quality. "
                    f"Pass --version "
                    f"{self.gold_definition_key.rsplit('.v', 1)[-1]} to score "
                    f"against the definition the key was written for."
                )
            ),
            "pooled": case_ppv_sensitivity(matrix),
            "per_study": {
                study: case_ppv_sensitivity(cm) for study, cm in sorted(per_study.items())
            },
            "verdict_confusion": matrix.to_dict(),
            "verdict_confusion_matrix": matrix,
            "state_confusion": state_matrix.to_dict(),
            "state_confusion_matrix": state_matrix,
            "counts_by_verdict": _count(assignments, "verdict"),
            "counts_by_state": _count(assignments, "evidence_state"),
            "review_set_size": sum(1 for a in assignments if a.verdict == "review"),
            "subjects": len(assignments),
        }

    # -- retrieval ----------------------------------------------------------

    def retrieval_metrics(self) -> dict[str, Any]:
        index = self.pipeline.index()
        catalog = self.pipeline.catalog
        from ..retrieval.query import retrieve

        concept = self.definition.concept.primary
        relevant_by_study: dict[str, set[str]] = defaultdict(set)
        for row in self.gold:
            if row.get("concept") == concept and row.get("assertion") == "present":
                relevant_by_study[row["study_id"]].add(row["doc_id"])

        per_query: list[dict[str, Any]] = []
        for study in sorted(relevant_by_study):
            relevant = relevant_by_study[study]
            result = retrieve(
                index, catalog, concept=concept, assertion=["present"],
                studies=[study], top_k=1000,
            )
            ranked = _unique_docs(result)
            per_query.append(
                {
                    "study": study,
                    "relevant": len(relevant),
                    "returned": len(ranked),
                    "mrr": round(reciprocal_rank(ranked, relevant), 4),
                    **{
                        f"recall@{k}": round(recall_at_k(ranked, relevant, k), 4)
                        for k in _RECALL_KS
                    },
                    **{
                        f"ceiling@{k}": round(recall_ceiling_at_k(relevant, k), 4)
                        for k in _RECALL_KS
                    },
                    **{
                        f"precision@{k}": round(precision_at_k(ranked, relevant, k), 4)
                        for k in _RECALL_KS
                    },
                }
            )

        pooled_relevant = {d for docs in relevant_by_study.values() for d in docs}
        with_filter = retrieve(
            index, catalog, concept=concept, assertion=["present"], top_k=1000
        )
        without_filter = retrieve(index, catalog, concept=concept, top_k=1000)

        gold_absent = {
            row["doc_id"] for row in self.gold
            if row.get("concept") == concept and row.get("assertion") == "absent"
        }

        def negation_view(result) -> dict[str, Any]:
            docs = _unique_docs(result)
            returned_absent = sum(1 for d in docs if d in gold_absent)
            return {
                "returned": len(result.records),
                "distinct_documents": len(docs),
                "records_with_assertion_absent": result.negation_false_positives,
                "negation_false_positive_rate": round(
                    result.negation_false_positive_rate, 4
                ),
                "gold_negated_documents_returned": returned_absent,
                "mrr": round(reciprocal_rank(docs, pooled_relevant), 4),
                **{
                    f"recall@{k}": round(recall_at_k(docs, pooled_relevant, k), 4)
                    for k in _RECALL_KS
                },
                **{
                    f"ceiling@{k}": round(recall_ceiling_at_k(pooled_relevant, k), 4)
                    for k in _RECALL_KS
                },
                **{
                    f"precision@{k}": round(precision_at_k(docs, pooled_relevant, k), 4)
                    for k in _RECALL_KS
                },
            }

        return {
            "concept": concept,
            "expanded_terms": with_filter.expanded_terms,
            "gold_relevant_documents": len(pooled_relevant),
            "gold_negated_documents": len(gold_absent),
            "per_study": per_query,
            "assertion_filter_on": negation_view(with_filter),
            "assertion_filter_off": negation_view(without_filter),
            "mean_mrr_per_study": round(
                sum(q["mrr"] for q in per_query) / len(per_query), 4
            ) if per_query else 0.0,
            "dense_available": with_filter.dense_available,
            "notes": with_filter.notes,
        }

    # -- stability ----------------------------------------------------------

    def stability_check(self, repeats: int = 3) -> dict[str, Any]:
        """Do repeated invocations produce byte-identical output?"""
        run_ids: list[str] = []
        result_hashes: list[str] = []
        event_hashes: list[str] = []
        for _ in range(repeats):
            events = self.pipeline.engine().extract_store(self.pipeline.store)
            event_hashes.append(
                hash_payload([e.model_dump(mode="json") for e in events], length=32)
            )
            manifest = execute(self.pipeline, self.definition)
            run_ids.append(manifest.run_id)
            result_hashes.append(manifest.results_hash)
        return {
            "repeats": repeats,
            "run_ids": run_ids,
            "result_hashes": result_hashes,
            "extraction_hashes": event_hashes,
            "run_id_stable": len(set(run_ids)) == 1,
            "results_stable": len(set(result_hashes)) == 1,
            "extraction_stable": len(set(event_hashes)) == 1,
        }

    # -- definition sensitivity --------------------------------------------

    def sensitivity_sweep(
        self, sweeps: Sequence[dict[str, Any]] | None = None
    ) -> dict[str, Any]:
        """Re-run case assignment across a sweep of one rule parameter.

        The variants are derived in memory from the frozen definition and are
        never written to disk: a sweep explores what a change would do, it does
        not publish a new version.
        """
        sweeps = sweeps or [
            {
                "parameter": "glucose threshold (rule 'supported')",
                "values": [70, 63, 54, 45],
                "apply": _set_glucose_threshold,
                "note": (
                    "70 mg/dL is the ADA Level 1 glucose alert value; 54 is "
                    "Level 2. Studies vary in which they used."
                ),
            },
            {
                "parameter": "window maximum (days from anchor)",
                "values": [28, 14, 7, 3],
                "apply": _set_window_max,
                "note": "How long after a dose escalation an event still counts.",
            },
        ]

        results: list[dict[str, Any]] = []
        for sweep in sweeps:
            rows = []
            for value in sweep["values"]:
                variant = sweep["apply"](self.definition, value)
                assignments = self.pipeline.evaluate(variant)
                counts = _count(assignments, "verdict")
                rows.append(
                    {
                        "value": value,
                        "case": counts.get("case", 0),
                        "review": counts.get("review", 0),
                        "excluded": counts.get("excluded", 0),
                        "states": _count(assignments, "evidence_state"),
                    }
                )
            baseline = next(
                (r for r in rows if r["value"] in sweep["values"][:1]), rows[0]
            )
            results.append(
                {
                    "parameter": sweep["parameter"],
                    "note": sweep.get("note", ""),
                    "baseline_value": baseline["value"],
                    "rows": rows,
                    "case_count_range": [
                        min(r["case"] for r in rows), max(r["case"] for r in rows)
                    ],
                }
            )
        return {"sweeps": results}

    # -- everything ---------------------------------------------------------

    def run_all(self) -> dict[str, Any]:
        return {
            "generated_at": _dt.datetime.now(_dt.timezone.utc).isoformat(
                timespec="seconds"
            ),
            "snapshot_id": self.pipeline.snapshot_id,
            "extractor_version": self.pipeline.extractor_version,
            "definition": {
                "id": self.definition.id,
                "version": self.definition.version,
                "status": self.definition.status,
                "hash": self.definition.definition_hash,
                "label": self.definition.label,
            },
            "corpus": self.pipeline.store.summary(),
            "extraction": self.extraction_metrics(),
            "phenotype": self.phenotype_metrics(),
            "retrieval": self.retrieval_metrics(),
            "stability": self.stability_check(),
            "sensitivity": self.sensitivity_sweep(),
        }


# --------------------------------------------------------------------------
# Definition variants for the sweep
# --------------------------------------------------------------------------


def _variant(definition: PhenotypeDefinition, label: str) -> PhenotypeDefinition:
    clone = definition.model_copy(deep=True)
    clone.status = "draft"
    clone.source_path = ""
    clone.definition_hash = hash_payload(
        {"base": definition.definition_hash, "variant": label}, length=16
    )
    return clone


def _set_glucose_threshold(
    definition: PhenotypeDefinition, value: float
) -> PhenotypeDefinition:
    clone = _variant(definition, f"glucose<{value}")
    for rule in clone.evidence_rules:
        _walk_and_set_lab(rule.when, "GLUCOSE", value)
    return clone


def _walk_and_set_lab(condition: Any, test: str, value: float) -> None:
    if isinstance(condition, list):
        for item in condition:
            _walk_and_set_lab(item, test, value)
        return
    if not isinstance(condition, dict):
        return
    for key, body in condition.items():
        if key == "lab" and isinstance(body, dict) and body.get("test") == test:
            body["value"] = value
        else:
            _walk_and_set_lab(body, test, value)


def _set_window_max(
    definition: PhenotypeDefinition, value: int
) -> PhenotypeDefinition:
    clone = _variant(definition, f"window<={value}")
    if clone.window is not None:
        clone.window.max = int(value)
    return clone


