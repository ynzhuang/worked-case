"""The evaluation harness.

Five things get measured, and each of them exists to answer a question a
reviewer would actually ask.

**Extraction** — does the extractor recover what the narrative says?  Reported
per field, broken out by assertion class and by narrative pattern, with an
assertion confusion matrix.  The breakouts matter more than the pooled number:
a pooled F1 hides that the extractor is excellent on explicit mentions and
weaker on vague temporal phrasing, and that difference changes how a result
should be read.

**Phenotype** — does the definition put the right subjects in the right bucket?
PPV and sensitivity against the gold case labels, per study and pooled, plus the
full case/review/excluded confusion.

**Retrieval** — recall@k, MRR, and a negation false positive rate measured with
the assertion filter on and off.  That contrast is the headline number, because
it quantifies what structured assertion buys.

**Stability** — the same corpus, config and definition produce an identical run
hash across invocations.

**Definition sensitivity** — re-run case assignment across a sweep of one rule
parameter and report how the case count moves.  This makes definitional drift a
measurement rather than an argument.

Gold labels are the generator's intent.  Metrics against them measure recovery
of a deliberately planted signal, which is a weaker claim than performance on
real clinical text, and the report says so.
"""

