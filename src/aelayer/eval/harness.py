DISCLAIMER = (
    "All numbers below are computed on a synthetic corpus generated by this "
    "repository. Gold labels are the generator's intent, so these figures "
    "measure whether the pipeline recovers a signal that was deliberately "
    "planted. They are not an estimate of performance on real clinical text."
)

INVARIANCE_CAVEAT = (
    "Consistency across representations is not clinical validity. A pipeline "
    "can be perfectly consistent and consistently wrong. This section is a "
    "robustness check layered on the phenotype and extraction numbers; it does "
    "not replace them, and a high agreement rate here is not evidence that the "
    "case definition is clinically correct."
)

SILENCE_CAVEAT = (
    "The distinction below is the one the whole two-field design exists for. "
    "An observed 'absent' puts a subject in the denominator as a non_case; "
    "silence does not put them anywhere. A system that reads one as the other "
    "will report a rate that looks precise and is wrong by however many "
    "subjects were never examined."
)


def case_metrics(matrix: ConfusionMatrix) -> dict[str, Any]:
    """PPV and sensitivity for `case`, with not-ascertainable reported apart.

    The not-ascertainable rate is computed over everything the definition was
    asked about, because that is the number a reader needs: how much of the
    cohort question this corpus simply cannot answer.
    """
    tp = matrix.get("case", "case")
    fp = sum(matrix.get(g, "case") for g in matrix.labels if g != "case")
    fn = sum(matrix.get("case", p) for p in matrix.labels if p != "case")
    prf = PRF(tp=tp, fp=fp, fn=fn)
    predicted_na = sum(matrix.get(g, "not_ascertainable") for g in matrix.labels)
    true_na = sum(matrix.get("not_ascertainable", p) for p in matrix.labels)
    return {
        "ppv": round(prf.precision, 4),
        "sensitivity": round(prf.recall, 4),
        "f1": round(prf.f1, 4),
        "tp": tp, "fp": fp, "fn": fn,
        "gold_cases": prf.support,
        "predicted_cases": prf.predicted,
        "records": matrix.total,
        "not_ascertainable_predicted": predicted_na,
        "not_ascertainable_gold": true_na,
        "not_ascertainable_rate": (
            round(predicted_na / matrix.total, 4) if matrix.total else 0.0
        ),
        "not_ascertainable_agreement": round(
            matrix.get("not_ascertainable", "not_ascertainable") / true_na, 4
        ) if true_na else 0.0,
    }


@dataclass
class EvaluationHarness:
    pipeline: Pipeline
    definition: PhenotypeDefinition
    records: list[CanonicalAERecord] = _dc_field(default_factory=list)
    result: EvaluationResult | None = None

    @classmethod
    def build(
        cls, pipeline: Pipeline, definition: PhenotypeDefinition
    ) -> "EvaluationHarness":
        records = pipeline.records()
        return cls(
            pipeline=pipeline, definition=definition, records=records,
            result=pipeline.evaluate(definition, records=records),
        )

    @property
    def assignments(self) -> list[CaseAssignment]:
        return self.result.assignments if self.result else []

    # -- gold ---------------------------------------------------------------

    def gold(self) -> dict[str, dict[str, Any]]:
        """Gold keyed by the canonical record id.

        The source-record grain, on both sides. The generator writes one gold
        row per rendered event, and that is the same grain the evaluator
        assigns verdicts at, so the join needs no assumption.
        """
        by_source = self.pipeline.store.gold_by_record()
        return {
            record.record_id: by_source[record.source_record_id]
            for record in self.records
            if record.source_record_id in by_source
        }

    # -- phenotype ----------------------------------------------------------

    def phenotype(self) -> dict[str, Any]:
        gold = self.gold()
        matrix = ConfusionMatrix(labels=list(VERDICTS))
        per_study: dict[str, ConfusionMatrix] = {}
        per_profile: dict[str, ConfusionMatrix] = {}

        for assignment in self.assignments:
            truth = gold.get(assignment.record_id)
            if truth is None:
                continue
            matrix.add(truth["true_verdict"], assignment.verdict)
            per_study.setdefault(
                assignment.study_id, ConfusionMatrix(labels=list(VERDICTS))
            ).add(truth["true_verdict"], assignment.verdict)
            per_profile.setdefault(
                assignment.profile, ConfusionMatrix(labels=list(VERDICTS))
            ).add(truth["true_verdict"], assignment.verdict)

        return {
            "evaluated_definition": self.definition.key,
            "records": len(self.assignments),
            "matched_to_gold": matrix.total,
            "pooled": case_metrics(matrix),
            "verdict_confusion": matrix.to_dict(),
            "verdict_matrix": matrix,
            "counts_by_verdict": dict(
                sorted(collections.Counter(
                    a.verdict for a in self.assignments
                ).items())
            ),
            "per_study": {s: case_metrics(m) for s, m in sorted(per_study.items())},
            "per_profile": {
                p: case_metrics(m) for p, m in sorted(per_profile.items())
            },
            "attribute_sources": dict(sorted(collections.Counter(
                variable for a in self.assignments if a.verdict == "case"
                for variable in a.attribute_sources.values()
            ).items())),
            "attribute_methods": dict(sorted(collections.Counter(
                method for a in self.assignments if a.verdict == "case"
                for method in a.attribute_methods.values()
            ).items())),
            "cases_depending_on_text": sum(
                1 for a in self.assignments
                if a.verdict == "case" and a.used_text_extraction
            ),
        }

    # -- denominators -------------------------------------------------------

    def denominators(self) -> dict[str, Any]:
        from ..models import DENOMINATOR_NOTE

        return {
            "note": DENOMINATOR_NOTE,
            "per_study": [d.to_dict() for d in self.result.denominators()],
            "overall": self.result.overall().to_dict(),
        }

    # -- value ablation -----------------------------------------------------

    def ablation(self) -> dict[str, Any]:
        """Three cumulative stages, ending in a decision. See ``ablation.py``."""
        report = run_ablation(
            self.definition, self.pipeline.store, self.pipeline.configs,
            self.pipeline.backend_preference,
        )
        return report.to_dict()

    # -- silence versus a documented negative -------------------------------

    def assertion_confusion(
        self, modifier: str = "mucosal_involvement"
    ) -> dict[str, Any]:
        """Does the system tell a documented "no" from nobody having looked?

        Scored per source record against the generator's own labels, on the
        two fields together: what the source asserted, and whether it said
        anything at all.
        """
        gold = self.pipeline.store.gold_by_record()
        labels = [*ASSERTIONS, "silent"]
        matrix = ConfusionMatrix(labels=labels)
        availability = ConfusionMatrix(labels=list(AVAILABILITIES))
        confusions: list[dict[str, Any]] = []

        for record in self.records:
            truth = gold.get(record.source_record_id)
            if truth is None:
                continue
            attribute = record.modifiers.get(modifier)
            # What the record *should* be readable as: the assertion a route
            # actually carries, or silence when no route carries one.
            expected_assertion = (
                truth.get("structured_assertion")
                or truth.get("text_assertion")
                or "silent"
            )
            actual_assertion = (
                attribute.assertion if attribute and attribute.observed else "silent"
            )
            matrix.add(expected_assertion, actual_assertion)
            availability.add(
                truth.get("true_availability") or "unresolved",
                attribute.availability if attribute else "unresolved",
            )
            if expected_assertion != actual_assertion:
                confusions.append({
                    "source_record_id": record.source_record_id,
                    "profile": record.profile,
                    "expected": expected_assertion,
                    "actual": actual_assertion,
                    "note": attribute.note if attribute else "",
                })

        negatives_lost = sum(
            matrix.get("absent", p) for p in matrix.labels if p != "absent"
        )
        silence_invented = sum(
            matrix.get("silent", p) for p in matrix.labels if p != "silent"
        )
        return {
            "caveat": SILENCE_CAVEAT,
            "modifier": modifier,
            "assertion_confusion": matrix.to_dict(),
            "assertion_matrix": matrix,
            "availability_confusion": availability.to_dict(),
            "accuracy": round(matrix.accuracy, 4),
            "documented_negatives_read_as_something_else": negatives_lost,
            "silence_read_as_an_assertion": silence_invented,
            "documented_negatives_recovered": matrix.get("absent", "absent"),
            "examples": confusions[:10],
        }

    # -- invariance ---------------------------------------------------------

    def invariance(self) -> dict[str, Any]:
        """One truth, seven renderings: does the verdict agree where it can?"""
        gold = self.gold()
        by_truth: dict[str, dict[str, dict[str, Any]]] = collections.defaultdict(dict)
        for assignment in self.assignments:
            truth = gold.get(assignment.record_id)
            if truth is None or truth.get("cohort") != "shared":
                continue
            by_truth[truth["truth_id"]][assignment.profile] = {
                "verdict": assignment.verdict,
                "reference": truth["verdict_if_readable"],
                "readable": truth["readable"],
                "reason": assignment.reason,
            }

        comparable = {t: b for t, b in by_truth.items() if len(b) >= 2}
        agreeing = 0
        # Agreement *where the evidence supports it*: a rendering that could
        # not record the modifier at all is not expected to reach the same
        # verdict, and counting it as a disagreement would punish the system
        # for the study's collection decision.
        supported_agreeing = 0
        supported_total = 0
        discordant: list[dict[str, Any]] = []

        for truth_id, body in sorted(comparable.items()):
            if len({v["verdict"] for v in body.values()}) == 1:
                agreeing += 1
            supported = {p: v for p, v in body.items() if v["readable"]}
            if supported:
                supported_total += 1
                if len({v["verdict"] for v in supported.values()}) == 1:
                    supported_agreeing += 1
                else:
                    discordant.append({
                        "truth_id": truth_id,
                        "reference": next(iter(body.values()))["reference"],
                        "verdicts": {p: v["verdict"] for p, v in sorted(body.items())},
                        "example_reason": sorted(supported.items())[0][1]["reason"],
                    })

        total = len(comparable)
        return {
            "caveat": INVARIANCE_CAVEAT,
            "truths_compared": total,
            "raw_agreement": round(agreeing / total, 4) if total else 0.0,
            "agreement_where_evidence_supports_it": round(
                supported_agreeing / supported_total, 4
            ) if supported_total else 0.0,
            "truths_with_supporting_evidence": supported_total,
            "discordant_count": len(discordant),
            "discordant": discordant[:20],
            "verdicts_by_profile": {
                profile: dict(sorted(collections.Counter(
                    body[profile]["verdict"] for body in comparable.values()
                    if profile in body
                ).items()))
                for profile in sorted(
                    {p for body in comparable.values() for p in body}
                )
            },
        }

    # -- reproducibility ----------------------------------------------------

    def reproducibility(self, repeats: int = 2) -> dict[str, Any]:
        manifest_ids: list[str] = []
        result_hashes: list[str] = []
        record_hashes: list[str] = []
        for _ in range(repeats):
            records = self.pipeline.records(refresh=True)
            record_hashes.append(
                hash_payload([r.model_dump(mode="json") for r in records], length=32)
            )
            manifest, _assignments = execute(
                self.pipeline, self.definition, save=False
            )
            manifest_ids.append(manifest.manifest_id)
            result_hashes.append(manifest.results_hash)
        return {
            "repeats": repeats,
            "manifest_ids": manifest_ids,
            "result_hashes": result_hashes,
            "manifest_id_stable": len(set(manifest_ids)) == 1,
            "results_stable": len(set(result_hashes)) == 1,
            "normalization_stable": len(set(record_hashes)) == 1,
        }

    # -- silver and transport ----------------------------------------------

    def silver(self, modifier: str = "mucosal_involvement") -> dict[str, Any]:
        harness = SilverHarness(
            self.pipeline.configs, self.pipeline.store, self.pipeline.engine()
        )
        report = harness.run(self.records, modifier)
        body = report.to_dict()
        body["adjudication_queue_size"] = len(report.adjudication_queue())
        return body

    def transport(self, holdout: Sequence[str] | None = None) -> dict[str, Any]:
        from .transport import transportability

        return transportability(self.pipeline, self.definition, holdout)

    # -- everything ---------------------------------------------------------

    def run_all(self, holdout: Sequence[str] | None = None) -> dict[str, Any]:
        return {
            "generated_at": _dt.datetime.now(_dt.timezone.utc).isoformat(
                timespec="seconds"
            ),
            "disclaimer": DISCLAIMER,
            "silver_caveats": list(SILVER_CAVEATS),
            "versions": self.pipeline.versions(),
            "definition": {
                "id": self.definition.id,
                "version": self.definition.version,
                "status": self.definition.status,
                "hash": self.definition.definition_hash,
                "label": self.definition.label,
            },
            "corpus": {
                **self.pipeline.store.summary(),
                "records": len(self.records),
                "episodes": len(self.pipeline.episodes().episodes),
            },
            "phenotype": self.phenotype(),
            "denominators": self.denominators(),
            "ablation": self.ablation(),
            "silver": self.silver(),
            "assertion": self.assertion_confusion(),
            "transport": self.transport(holdout),
            "invariance": self.invariance(),
            "reproducibility": self.reproducibility(),
        }


def run_evaluation(
    pipeline: Pipeline | None = None,
    definition_id: str = "cutaneous_mucosal",
    version: int | None = None,
    report_path: str | Path | None = None,
    holdout: Sequence[str] | None = None,
) -> tuple[dict[str, Any], Path | None]:
    pipeline = pipeline or Pipeline.load(store_path=paths.STORE_DB)
    definition = pipeline.definition(definition_id, version)
    results = EvaluationHarness.build(pipeline, definition).run_all(holdout)

    written: Path | None = None
    if report_path is not None:
        from .report import render_markdown

        target = Path(report_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_markdown(results), encoding="utf-8")
        written = target
    return results, written
