@app.get("/eval/silver")
def silver_endpoint(
    attribute: str = "location", limit: int = Query(25, le=500)
) -> dict[str, Any]:
    """Extraction scored against the study's own structured field."""
    from .silver import SilverHarness

    pipeline = get_pipeline()
    harness = SilverHarness(pipeline.configs, pipeline.store, pipeline.engine())
    eligible = harness.eligible_profiles(attribute)
    if not eligible:
        raise HTTPException(
            status_code=400,
            detail=(
                f"no profile records {attribute} both structurally and in text, "
                f"so there is nothing to build a silver standard from"
            ),
        )
    report = harness.run(pipeline.records(), attribute, eligible)
    body = report.to_dict()
    body["adjudication_queue"] = report.adjudication_queue()[:limit]
    return body


