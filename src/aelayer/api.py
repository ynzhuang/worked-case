NOTICE = (
    "All data is synthetic and generated by this repository. The extraction "
    "backend is a configurable rule and lexicon baseline unless an LLM backend "
    "was configured; it is not a trained clinical NLP model. Coded terms in "
    "the concept catalogue are illustrative placeholders, not licensed "
    "dictionary content."
)

app = FastAPI(
    title="Adverse event evidence layer",
    version="2.0.0",
    description=(
        "Source-faithful canonical AE records, derived episodes above them, "
        "and versioned phenotype definitions evaluated over the episodes. "
        + NOTICE
    ),
)


@lru_cache(maxsize=1)
def _pipeline_singleton() -> Pipeline:
    return Pipeline.load(store_path=paths.STORE_DB)


def get_pipeline() -> Pipeline:
    try:
        return _pipeline_singleton()
    except (IngestError, ConfigError, SemanticsError) as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc


def reset_pipeline() -> None:
    _pipeline_singleton.cache_clear()


def _runs_dir() -> Path:
    return paths.RUNS_DIR


def _manifests() -> ManifestStore:
    return ManifestStore(_runs_dir())


def _results() -> ResultStore:
    return ResultStore(_runs_dir() / "results")


