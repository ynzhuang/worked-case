"""HTTP API.

Thin. Every endpoint delegates to the same pipeline the CLI uses, so the API
and the CLI cannot disagree about which definition version produced a number.

Four things this API does deliberately:

**Attributes carry their route.** Every record response says which variable
each value came from, by which method, and — separately — what the source
asserted and whether it said anything at all. In this layer those are part of
the fact rather than metadata about it.

**Assertion and availability are separate query parameters.** There is no
single "missing" filter, because a documented negative and an uncollected
variable are different populations and a combined filter would invite treating
them as one.

**Discovery and cohort selection are different endpoints.** ``/retrieve``
returns adjudicated records; ``/discover`` returns candidates and says so in
the payload. No parameter turns one into the other.

**There is no approval gate.** ``/agent/ask`` compiles, executes, and returns
the trace. What makes a number checkable is that it can be followed back to
source afterwards, by someone who was not in the room. A question that
conflicts with the definition it names returns 409 and no number at all.
"""

