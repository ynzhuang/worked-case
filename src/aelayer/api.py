@app.post("/agent/ask")
def agent_ask(request: AskRequest) -> JSONResponse:
    """Compile and execute, and return the trace that makes it checkable."""
    from .agent import AgentSession

    session = AgentSession(get_pipeline(), request.question, backend=request.backend)
    result = session.compile()
    if result.needs_clarification:
        return JSONResponse(
            {
                "executed": False,
                "clarification": result.clarification.model_dump(mode="json"),
                "detail": (
                    "The question leaves a rule underdetermined. Nothing was "
                    "executed and no number was produced."
                ),
            },
            status_code=409,
        )
    package, manifest = session.execute(
        manifest_store=_manifests(), save=request.save
    )
    payload = package.to_dict()
    payload["executed"] = True
    payload["manifest"] = manifest.model_dump(mode="json")
    return JSONResponse(payload)


@app.get("/trace/{manifest_id}")
def trace_endpoint(manifest_id: str, verdict: str = "case") -> dict[str, Any]:
    from .agent import render_trace, trace_number

    pipeline = get_pipeline()
    try:
        manifest = _manifests().load(manifest_id)
        assignments = _results().read(manifest_id)
    except ReplayError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc

    count = sum(1 for a in assignments if a.verdict == verdict)
    chain = trace_number(
        number=count, label=f"{verdict} count", manifest=manifest,
        assignments=assignments, episodes=pipeline.episodes(),
        records=pipeline.records(), verdict=verdict,
    )
    return {
        "manifest_id": manifest_id,
        "number": count,
        "complete": chain.complete,
        "broken_at": chain.broken_at,
        "links": [link.model_dump(mode="json") for link in chain.links],
        "rendered": render_trace(chain),
    }


