def create_app(data_dir: str | Path | None = None) -> FastAPI:
    """The app, with the pipeline pinned to a chosen snapshot."""
    if data_dir is not None:
        reset_pipeline()
        _pipeline_singleton.__wrapped__.__defaults__ = ()  # type: ignore[attr-defined]

        @lru_cache(maxsize=1)
        def _loader() -> Pipeline:
            return Pipeline.load(data_dir, store_path=paths.STORE_DB)

        globals()["_pipeline_singleton"] = _loader
    return app
