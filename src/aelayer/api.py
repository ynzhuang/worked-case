@app.post("/evaluate")
def evaluate(request: EvaluateRequest) -> dict[str, Any]:
    pipeline = get_pipeline()
    try:
        definition = pipeline.definition(
            request.definition_id, request.version, allow_draft=request.allow_draft
        )
    except DefinitionError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    manifest, assignments = execute(
        pipeline, definition, studies=request.studies or None, actor="api",
        manifest_store=_manifests(), result_store=_results(), save=request.save,
    )
    if request.save:
        pipeline.index().record_assignments(assignments)
    return {
        "manifest": manifest.model_dump(mode="json"),
        "assignments": [a.model_dump(mode="json") for a in assignments],
        "not_ascertainable": [
            a.model_dump(mode="json") for a in assignments
            if a.verdict == "not_ascertainable"
        ],
    }


@app.get("/retrieve")
def retrieve_endpoint(
    concept: Optional[str] = None,
    region: Optional[str] = None,
    location: list[str] = Query(default=[]),
    method: list[str] = Query(default=[]),
    profile: list[str] = Query(default=[]),
    studies: list[str] = Query(default=[]),
    verdict: list[str] = Query(default=[]),
    window_min: Optional[int] = None,
    window_max: Optional[int] = None,
    top_k: int = Query(50, le=1000),
) -> dict[str, Any]:
    """The precise path: adjudicated episodes, usable as a cohort."""
    from .retrieval.query import retrieve

    pipeline = get_pipeline()
    window = (
        (window_min, window_max)
        if window_min is not None and window_max is not None else None
    )
    try:
        result = retrieve(
            pipeline.index(), pipeline.catalog, concept=concept, region=region,
            location=location or None, method=method or None,
            profile=profile or None, studies=studies or None,
            verdict=verdict or None, window=window, top_k=top_k,
        )
    except ConfigError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return result.to_dict()


