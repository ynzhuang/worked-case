"""HTTP API.

Thin.  Every endpoint delegates to the same pipeline the CLI uses, so the API
and the CLI cannot disagree about which definition version produced a number.

Two things this API does differently from the obvious design.

**There is no approval gate.**  A compiled specification is returned, and it is
executed.  Approving a specification you cannot independently evaluate is
ceremony; what makes a number checkable is that ``/trace`` walks it back to the
sentence a site wrote, after the fact, by someone who was not in the room.

**Discovery and cohort selection are different endpoints.**  ``/retrieve``
returns episodes that a definition has adjudicated.  ``/discover`` returns
places in documents where a concept is named, and says in the payload that they
are candidates.  A caller cannot reach a denominator from the second one by
adding a parameter.
"""

