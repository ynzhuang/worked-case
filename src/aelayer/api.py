"""HTTP API.

Thin. Every endpoint delegates to the same pipeline the CLI uses, so the API and
the CLI cannot disagree about which definition version produced a number.

Three things this API does deliberately:

**Attributes carry their route.** Every record and episode response says which
variable each value came from and by which method, because in this layer that is
part of the fact rather than metadata about it.

**Discovery and cohort selection are different endpoints.** ``/retrieve``
returns adjudicated episodes; ``/discover`` returns candidates and says so in
the payload. No parameter turns one into the other.

**There is no approval gate.** ``/agent/ask`` compiles, executes, and returns
the trace. What makes a number checkable is that it can be followed back to
source afterwards, by someone who was not in the room.
"""

