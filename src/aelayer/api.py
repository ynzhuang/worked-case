@lru_cache(maxsize=1)
def _pipeline_singleton() -> Pipeline:
    return Pipeline.load(store_path=paths.STORE_DB)


def get_pipeline() -> Pipeline:
    try:
        return _pipeline_singleton()
    except (IngestError, ConfigError, ProfileError) as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc


def reset_pipeline() -> None:
    _pipeline_singleton.cache_clear()


def _runs_dir() -> Path:
    return paths.RUNS_DIR


def _manifests() -> ManifestStore:
    return ManifestStore(_runs_dir())


def _results() -> ResultStore:
    return ResultStore(_runs_dir() / "results")


def _attribute(attribute: Any) -> dict[str, Any]:
    """One attribute, with the two fields kept apart on the wire too."""
    return {
        "value": attribute.value,
        "assertion": attribute.assertion,
        "availability": attribute.availability,
        "observed": attribute.observed,
        "documented_negative": attribute.documented_negative,
        "method": attribute.method,
        "source": attribute.source,
        "source_variable": attribute.source_variable,
        "confidence": attribute.confidence,
        "versions": attribute.versions,
        "note": attribute.note,
        "prior_availability": attribute.prior_availability,
        "route": attribute.describe_route(),
        "evidence": [s.model_dump(mode="json") for s in attribute.evidence],
    }


