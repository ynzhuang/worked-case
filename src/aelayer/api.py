@app.post("/build")
def build(request: BuildRequest) -> dict[str, Any]:
    """Normalize, extract, reconcile, index — the whole path."""
    pipeline = get_pipeline()
    records = pipeline.records(refresh=request.refresh)
    episodes = pipeline.episodes(refresh=request.refresh)
    index = pipeline.index(refresh=request.refresh)
    violations = [
        {"record_id": r.source_record_id, "attributes": r.missing_provenance()}
        for r in records if not r.has_full_provenance()
    ]
    return {
        "records": len(records),
        "episodes": len(episodes),
        "mentions": index.meta().mention_count,
        **pipeline.versions(),
        "provenance_violations": violations,
        "backend_notes": list(pipeline.engine().notes),
    }


@app.get("/api/records")
def records(
    profile: Optional[str] = None,
    availability: Optional[str] = None,
    method: Optional[str] = None,
    limit: int = Query(50, le=500),
) -> dict[str, Any]:
    pipeline = get_pipeline()
    rows = pipeline.records()
    if profile:
        rows = [r for r in rows if r.profile == profile]
    if availability:
        rows = [r for r in rows if r.location.availability == availability]
    if method:
        rows = [r for r in rows if r.location.method == method]
    return {
        "count": len(rows),
        "records": [
            {
                "source_record_id": r.source_record_id,
                "study_id": r.study_id,
                "subject_id": r.subject_id,
                "profile": r.profile,
                "reported_term": r.reported_term.value,
                "coded_event": r.coded_event.value,
                "dictionary_version": r.dictionary_version,
                "concept": r.standardized_concept,
                "location": r.location.value,
                "location_method": r.location.method,
                "location_source": r.location.source_variable,
                "location_availability": r.location.availability,
            }
            for r in rows[:limit]
        ],
    }


@app.get("/api/records/{source_record_id}")
def record(source_record_id: str) -> dict[str, Any]:
    pipeline = get_pipeline()
    found = next(
        (r for r in pipeline.records() if r.source_record_id == source_record_id),
        None,
    )
    if found is None:
        raise HTTPException(status_code=404, detail=f"no record {source_record_id!r}")
    documents = pipeline.store.documents_of(source_record_id)
    return {
        "record": found.model_dump(mode="json"),
        "attributes": {
            name: _attribute(attribute)
            for name, attribute in found.attributes().items()
        },
        "documents": [
            {"doc_id": d.doc_id, "kind": d.kind, "text": d.full_text}
            for d in documents
        ],
        "supplemental": pipeline.store.supplemental_for(source_record_id),
        "provenance_complete": found.has_full_provenance(),
    }


