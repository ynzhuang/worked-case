@app.get("/api/episodes/{episode_id}")
def episode(episode_id: str) -> dict[str, Any]:
    pipeline = get_pipeline()
    found = next(
        (e for e in pipeline.episodes() if e.episode_id == episode_id), None
    )
    if found is None:
        raise HTTPException(status_code=404, detail=f"no episode {episode_id!r}")
    by_id = {r.source_record_id: r for r in pipeline.records()}
    return {
        "episode": found.model_dump(mode="json"),
        "field_states": found.field_states,
        "field_notes": found.field_notes,
        "records": [
            by_id[rid].model_dump(mode="json")
            for rid in found.source_record_ids if rid in by_id
        ],
    }


