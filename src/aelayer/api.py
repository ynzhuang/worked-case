@app.post("/evaluate")
def evaluate(request: EvaluateRequest) -> dict[str, Any]:
    pipeline = get_pipeline()
    try:
        definition = pipeline.definition(
            request.definition_id, request.version, allow_draft=request.allow_draft
        )
    except DefinitionError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    manifest, assignments = execute(
        pipeline, definition,
        studies=request.studies or None,
        actor="api",
        manifest_store=_manifests(),
        result_store=_results(),
        save=request.save,
    )
    if request.save:
        pipeline.index().record_assignments(assignments)
    return {
        "manifest": manifest.model_dump(mode="json"),
        "assignments": [a.model_dump(mode="json") for a in assignments],
        "review_set": [
            a.model_dump(mode="json") for a in assignments if a.verdict == "review"
        ],
    }


@app.get("/retrieve")
def retrieve_endpoint(
    concept: Optional[str] = None,
    group: Optional[str] = None,
    text: Optional[str] = None,
    assertion: list[str] = Query(default=[]),
    evidence_state: list[str] = Query(default=[]),
    verdict: list[str] = Query(default=[]),
    studies: list[str] = Query(default=[]),
    representation: list[str] = Query(default=[]),
    provenance: list[str] = Query(default=[]),
    window_min: Optional[int] = None,
    window_max: Optional[int] = None,
    anchor: Optional[str] = None,
    linkage_review: Optional[bool] = None,
    definition_id: str = "te_symptomatic_hypoglycemia",
    definition_version: Optional[int] = None,
    top_k: int = Query(20, le=1000),
) -> dict[str, Any]:
    """The precise path: adjudicated episodes, usable as a cohort."""
    from .retrieval.query import retrieve

    pipeline = get_pipeline()
    window = (
        (window_min, window_max)
        if window_min is not None and window_max is not None
        else None
    )
    try:
        result = retrieve(
            pipeline.index(), pipeline.catalog,
            concept=concept, group=group, text=text,
            assertion=assertion or None,
            evidence_state=evidence_state or None,
            verdict=verdict or None,
            window=window, anchor=anchor,
            studies=studies or None,
            representation=representation or None,
            provenance=provenance or None,
            linkage_review=linkage_review,
            definition_id=definition_id,
            definition_version=definition_version,
            mode="precise", top_k=top_k,
        )
    except ConfigError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return result.to_dict()


@app.get("/discover")
def discover_endpoint(
    concept: Optional[str] = None,
    group: Optional[str] = None,
    text: Optional[str] = None,
    assertion: list[str] = Query(default=[]),
    studies: list[str] = Query(default=[]),
    match_kind: list[str] = Query(default=[]),
    mode: Literal["lexical", "dense", "hybrid"] = "lexical",
    top_k: int = Query(20, le=1000),
) -> dict[str, Any]:
    """The discovery path: narrative mentions, every one a candidate."""
    from .retrieval.query import discover

    pipeline = get_pipeline()
    try:
        result = discover(
            pipeline.index(), pipeline.catalog,
            concept=concept, group=group, text=text,
            assertion=assertion or None,
            studies=studies or None,
            match_kind=match_kind or None,
            mode=mode, top_k=top_k,
        )
    except ConfigError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    payload = result.to_dict()
    payload["usable_as_cohort"] = False
    payload["cohort_note"] = (
        "A mention is a place in a document where a concept is named, not an "
        "episode that occurred. These enter a cohort through adjudication or a "
        "definition version that claims them, never directly."
    )
    return payload


