@app.get("/definitions/{definition_id}/compare")
def definition_compare(
    definition_id: str, left: int, right: int,
    scope: Optional[str] = Query(
        default=None,
        description=(
            "Required. The scientific question this comparison serves; the "
            "capability is for evidence reuse, not for auditing past choices."
        ),
    ),
) -> dict[str, Any]:
    pipeline = get_pipeline()
    try:
        a = pipeline.definitions.get(definition_id, left, allow_draft=True)
        b = pipeline.definitions.get(definition_id, right, allow_draft=True)
    except DefinitionError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    try:
        comparison = diff_definitions(
            a, b, pipeline.snapshot_id, scope,
            pipeline.evaluate(a), pipeline.evaluate(b),
        )
    except ScopeRequired as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return comparison.to_dict()


@app.post("/definitions/candidate")
def definition_candidate(request: CandidateRequest) -> dict[str, Any]:
    """Render a proposed next version as YAML, without writing anything."""
    pipeline = get_pipeline()
    try:
        base = pipeline.definitions.get(
            request.definition_id, request.base_version, allow_draft=True
        )
    except DefinitionError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc

    body = base.model_dump(
        mode="json", exclude={"definition_hash", "source_path"}, by_alias=True
    )
    next_version = pipeline.definitions.next_version(base.id)
    body["version"] = next_version
    body["status"] = "draft"
    body["supersedes"] = base.key
    body["authors"] = [request.author]

    applied: list[str] = []
    for path, value in sorted(request.changes.items()):
        if _apply_change(body, path, value):
            applied.append(f"{path} = {value!r}")
        else:
            raise HTTPException(
                status_code=400, detail=f"no such definition path: {path!r}"
            )
    from .models import PhenotypeDefinition

    try:
        PhenotypeDefinition.model_validate(body)
    except Exception as exc:
        raise HTTPException(
            status_code=400, detail=f"the proposed candidate does not validate: {exc}"
        ) from exc
    return {
        "base": base.key,
        "candidate_version": next_version,
        "filename": f"{base.id}.v{next_version}.yaml",
        "applied_changes": applied,
        "yaml": yaml.safe_dump(body, sort_keys=False, allow_unicode=True),
        "note": (
            f"This is a candidate. {base.key} is {base.status} and has not been "
            f"modified. Save this file into config/phenotypes/ to publish it."
        ),
    }


def _apply_change(body: dict[str, Any], path: str, value: Any) -> bool:
    """Set one dotted path inside a definition body.

    A requirement is addressed by name — ``required_attributes.location.in`` —
    rather than by list index, so a candidate keeps its meaning if the order
    changes. The leaf must already exist: a change that invents a key is a typo
    in the caller's path, and adding it silently would produce a candidate that
    differs from the one asked for.
    """
    parts = path.split(".")
    node: Any = body
    for part in parts[:-1]:
        if isinstance(node, list):
            if part.isdigit() and int(part) < len(node):
                node = node[int(part)]
                continue
            match = next(
                (item for item in node
                 if isinstance(item, dict) and item.get("name") == part),
                None,
            )
            if match is None:
                return False
            node = match
            continue
        if isinstance(node, dict) and part in node:
            node = node[part]
            continue
        return False

    leaf = parts[-1]
    if isinstance(node, dict) and leaf in node:
        node[leaf] = value
        return True
    if isinstance(node, list) and leaf.isdigit() and int(leaf) < len(node):
        node[int(leaf)] = value
        return True
    return False


