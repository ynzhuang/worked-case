# Persistence
# --------------------------------------------------------------------------


class RunStore:
    def __init__(self, directory: str | Path | None = None):
        self.directory = Path(directory or paths.RUNS_DIR)

    def path_for(self, run_id: str) -> Path:
        return self.directory / f"{run_id}.json"

    def save(self, manifest: RunManifest) -> Path:
        self.directory.mkdir(parents=True, exist_ok=True)
        target = self.path_for(manifest.run_id)
        target.write_text(
            json.dumps(manifest.model_dump(mode="json"), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        return target

    def load(self, run_id: str) -> RunManifest:
        target = self.path_for(run_id)
        if not target.exists():
            known = [p.stem for p in sorted(self.directory.glob("*.json"))]
            raise ReplayError(
                f"no run {run_id!r} in {self.directory}."
                + (f" Known runs: {known}" if known else " No runs recorded yet.")
            )
        return RunManifest.model_validate_json(target.read_text(encoding="utf-8"))

    def list(self) -> list[RunManifest]:
        if not self.directory.exists():
            return []
        return sorted(
            (self.load(p.stem) for p in self.directory.glob("*.json")),
            key=lambda m: (m.created_at, m.run_id),
        )


@dataclass
class ReplayReport:
    run_id: str
    reproduced: bool
    original_hash: str
    replayed_hash: str
    differences: list[str]

    def summary(self) -> str:
        if self.reproduced:
            return (
                f"run {self.run_id} reproduced exactly "
                f"(results hash {self.original_hash})"
            )
        return (
            f"run {self.run_id} did NOT reproduce: "
            + "; ".join(self.differences)
        )


def replay(
    run_id: str,
    *,
    run_store: RunStore | None = None,
    data_dir: str | Path | None = None,
    phenotype_dir: str | Path | None = None,
) -> tuple[ReplayReport, RunManifest]:
    """Re-execute a recorded run and check it against what was recorded.

    Each of the three hashes is checked separately so that a failure says which
    input moved: the data, the config, or the definition.
    """
    store = run_store or RunStore()
    original = store.load(run_id)
    differences: list[str] = []

    pipeline = Pipeline.load(data_dir, phenotype_dir=phenotype_dir)
    if pipeline.snapshot_id != original.snapshot_id:
        differences.append(
            f"data snapshot differs (recorded {original.snapshot_id}, "
            f"now {pipeline.snapshot_id})"
        )
    if pipeline.extractor_version != original.extractor_version:
        differences.append(
            f"extractor version differs (recorded {original.extractor_version}, "
            f"now {pipeline.extractor_version})"
        )

    definition = pipeline.definitions.get(
        original.definition_id, original.definition_version, allow_draft=True
    )
    if definition.definition_hash != original.definition_hash:
        differences.append(
            f"definition {definition.key} has changed on disk "
            f"(recorded {original.definition_hash}, now {definition.definition_hash})"
        )

    replayed = execute(
        pipeline,
        definition,
        studies=original.spec.get("studies"),
        spec_extra={
            k: v for k, v in original.spec.items()
            if k not in ("definition_id", "definition_version", "studies", "concept")
        },
        limitations=original.limitations,
    )
    if replayed.results_hash != original.results_hash:
        differences.append(
            f"results hash differs (recorded {original.results_hash}, "
            f"replayed {replayed.results_hash})"
        )
    if replayed.run_id != original.run_id:
        differences.append(
            f"run id differs (recorded {original.run_id}, replayed {replayed.run_id})"
        )

    report = ReplayReport(
        run_id=run_id,
        reproduced=not differences,
        original_hash=original.results_hash,
        replayed_hash=replayed.results_hash,
        differences=differences,
    )
    return report, replayed
